    public void loadFoodsData() {
        SwingWorker<List<FoodResponseDto>, Void> worker = new SwingWorker<>() {
            @Override
            protected List<FoodResponseDto> doInBackground() throws Exception {
                return controller.getFoodsByStall(stallId);
            }

            @Override
            protected void done() {
                try {
                    List<FoodResponseDto> foods = get();
                    listModel.clear();
                    for (FoodResponseDto food : foods) {
                        listModel.addElement(food);
                    }
                } catch (Exception ex) {
                    JOptionPane.showMessageDialog(
                            FoodsPanel.this,
                            "Failed to load foods: " + ex.getMessage(),
                            "Error Loading Foods",
                            JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        };
        worker.execute();
    }

